/**
 * Intelligent helper to find the most relevant curated resources for a task.
 * Matches keywords across task title, description, and target goal.
 */
export function findMatchingResources(taskTitle = '', taskDescription = '', goalTitle = '', limit = 3) {
  const text = `${taskTitle} ${taskDescription} ${goalTitle}`.toLowerCase();

  const scored = curatedResources.map(res => {
    let score = 0;
    const titleLower = res.title.toLowerCase();
    const skillLower = res.skill_name.toLowerCase();
    const descLower = res.description.toLowerCase();

    // Direct skill match
    if (text.includes(skillLower)) score += 10;

    // Keyword checks
    const keywords = [
      'html', 'css', 'javascript', 'js', 'react', 'node', 'express', 'web', 'frontend', 'backend',
      'c ', 'c++', 'pointer', 'malloc', 'memory', 'struct', 'array', 'linked list', 'stack', 'queue',
      'tree', 'graph', 'hash', 'algorithm', 'dsa', 'complexity', 'big-o', 'sorting', 'search',
      'python', 'script', 'automation', 'java', 'oop', 'sql', 'database', 'sqlite', 'postgres',
      'git', 'github', 'commit', 'branch', 'machine learning', 'deep learning', 'pytorch', 'ai',
      'model', 'neural', 'vision', 'opencv', 'nlp', 'docker', 'container', 'linux', 'bash',
      'iot', 'esp32', 'arduino', 'security', 'owasp', 'xss', 'injection', 'cad', 'fusion', 'mechanics'
    ];

    for (const kw of keywords) {
      if (text.includes(kw)) {
        if (titleLower.includes(kw)) score += 5;
        if (skillLower.includes(kw)) score += 6;
        if (descLower.includes(kw)) score += 3;
      }
    }

    return { resource: res, score };
  });

  scored.sort((a, b) => b.score - a.score);

  // Return top matches with score > 0, or fallback to general good resources
  const topMatches = scored.filter(s => s.score > 0).slice(0, limit).map(s => s.resource);
  if (topMatches.length > 0) return topMatches;

  return curatedResources.slice(0, limit);
}
